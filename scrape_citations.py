import requests
import json
import time
from datetime import datetime
from typing import Dict, List, Set, Tuple, Optional
import csv

def fetch_with_retry(url: str, max_retries: int = 3) -> Optional[Dict]:
    """Fetch URL with retry logic and polite delay"""
    for attempt in range(max_retries):
        try:
            time.sleep(0.5)  # Be polite to the API
            response = requests.get(url, timeout=30)
            if response.status_code == 200:
                return response.json()
            else:
                print(f"  HTTP {response.status_code} for {url}")
                if attempt < max_retries - 1:
                    print(f"  Retrying in {2**attempt} seconds...")
                    time.sleep(2**attempt)
        except Exception as e:
            print(f"  Error fetching {url}: {e}")
            if attempt < max_retries - 1:
                print(f"  Retrying in {2**attempt} seconds...")
                time.sleep(2**attempt)
    return None

def format_authors(authors_list: List[Dict]) -> str:
    """Format authors as 'First Author et al.' or just the name if single author"""
    if not authors_list:
        return "Unknown"
    
    first_author = authors_list[0].get('author', {}).get('display_name', 'Unknown')
    if len(authors_list) == 1:
        return first_author
    else:
        return f"{first_author} et al."

def extract_work_id(openalex_url: str) -> str:
    """Extract work ID from OpenAlex URL"""
    if not openalex_url:
        return ""
    return openalex_url.split('/')[-1]

def create_work_node(work: Dict, node_type: str) -> Dict:
    """Create a standardized work node from OpenAlex work data"""
    work_id = extract_work_id(work.get('id', ''))
    
    # Handle venue safely
    venue = None
    primary_location = work.get('primary_location')
    if primary_location and primary_location.get('source'):
        venue = primary_location['source'].get('display_name')
    
    return {
        'id': work_id,
        'title': work.get('title', 'Unknown Title'),
        'authors': format_authors(work.get('authorships', [])),
        'year': work.get('publication_year'),
        'date': work.get('publication_date'),
        'cited_by_count': work.get('cited_by_count', 0),
        'venue': venue,
        'doi': work.get('doi'),
        'url': work.get('id'),
        'type': node_type
    }

