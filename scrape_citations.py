# Max concurrent API requests. OpenAlex polite pool handles this comfortably.
MAX_WORKERS = 5

def fetch_with_retry(url: str, max_retries: int = 3) -> Optional[Dict]:
    """Fetch URL with retry logic and polite delay"""
    for attempt in range(max_retries):
        try:
            time.sleep(0.1)  # Polite delay (was 0.5s — polite pool handles 10+ req/s)
            response = requests.get(url, timeout=30)
            if response.status_code == 200:
                return response.json()
            elif response.status_code == 429:
                wait = 2 ** (attempt + 1)
                print(f"  Rate limited (429). Waiting {wait}s...")
                time.sleep(wait)
            else:
                print(f"  HTTP {response.status_code} for {url}")
                if attempt < max_retries - 1:
                    print(f"  Retrying in {2**attempt} seconds...")
                    time.sleep(2**attempt)
        except Exception as e:
            print(f"  Error fetching {url}: {e}")
            if attempt < max_retries - 1:
                print(f"  Retrying in {2**attempt} seconds...")
                time.sleep(2**attempt)
    return None

def format_authors(authors_list: List[Dict]) -> str:
    """Format authors as 'First Author et al.' or just the name if single author"""
    if not authors_list:
        return "Unknown"

    first_author = authors_list[0].get('author', {}).get('display_name', 'Unknown')
    if len(authors_list) == 1:
        return first_author
    else:
        return f"{first_author} et al."

def extract_authors_list(authors_list: List[Dict]) -> List[str]:
    """Extract list of all author display names."""
    return [
        a.get('author', {}).get('display_name', '')
        for a in (authors_list or [])
        if a.get('author', {}).get('display_name')
    ]

def extract_work_id(openalex_url: str) -> str:
    """Extract work ID from OpenAlex URL"""
    if not openalex_url:
        return ""
    return openalex_url.split('/')[-1]

def create_work_node(work: Dict, node_type: str) -> Dict:
    """Create a standardized work node from OpenAlex work data"""
    work_id = extract_work_id(work.get('id', ''))

    # Handle venue safely
    venue = None
    primary_location = work.get('primary_location')
    if primary_location and primary_location.get('source'):
        venue = primary_location['source'].get('display_name')

    authorships = work.get('authorships', [])
    return {
        'id': work_id,
        'title': work.get('title', 'Unknown Title'),
        'authors': format_authors(authorships),
        'authors_list': extract_authors_list(authorships),
        'year': work.get('publication_year'),
        'date': work.get('publication_date'),
        'cited_by_count': work.get('cited_by_count', 0),
        'venue': venue,
        'doi': work.get('doi'),
        'url': work.get('id'),
        'type': node_type
    }

def _fetch_citing_for_work(args: Tuple) -> Tuple[str, List[Dict], set]:
    """
    Fetch all citing papers for a single author work.
    Returns (work_id, list_of_citing_nodes, set_of_edges).
    Runs in a worker thread — no shared state written here.
    """
    work, EMAIL = args
    work_id = extract_work_id(work.get('id', ''))
    work_title = work.get('title', 'Unknown')[:50]
    cited_by_count = work.get('cited_by_count', 0)

    # No API call needed for uncited works
    if cited_by_count == 0:
        return work_id, [], set()

    citing_papers = []
    cursor = "*"

    while cursor:
        citing_url = (
            f"https://api.openalex.org/works"
            f"?filter=cites:{work_id}&sort=cited_by_count:desc&per_page=200&cursor={cursor}&mailto={EMAIL}"
        )
        citing_data = fetch_with_retry(citing_url)

        if not citing_data:
            print(f"    Failed to fetch citing papers for {work_title}")
            break

        batch = citing_data.get('results', [])
        citing_papers.extend(batch)
        cursor = citing_data.get('meta', {}).get('next_cursor')

        if len(citing_papers) >= 2000:
            print(
                f"    Warning: hit 2000-paper cap for '{work_title}' "
                f"(actual cited_by_count: {cited_by_count}). Kept top {len(citing_papers)} by citation count."
            )
            break
        if not cursor:
            break

    nodes_out = [create_work_node(cw, 'citing') for cw in citing_papers]
    edges_out = {(n['id'], work_id) for n in nodes_out}
    return work_id, nodes_out, edges_out


def _fetch_reference_batch(args: Tuple) -> List[Dict]:
    """
    Fetch metadata for a batch of reference IDs.
    Returns list of work nodes. Runs in a worker thread.
    """
    batch_ids, EMAIL = args
    id_filter = '|'.join(batch_ids)
    refs_url = (
        f"https://api.openalex.org/works"
        f"?filter=openalex:{id_filter}&per_page=200&mailto={EMAIL}"
    )
    refs_data = fetch_with_retry(refs_url)
    if refs_data:
        return [create_work_node(rw, 'reference') for rw in refs_data.get('results', [])]
    return []


TYPE_PRIORITY = {'author': 4, 'mutual': 3, 'citing': 2, 'reference': 1, 'level2': 0}


def merge_versions(nodes: dict, edges: set) -> Tuple[dict, set]:
    """
    Detect and merge preprint/published version pairs across all node types.

    Match criteria (either is sufficient):
      1. Same normalized DOI (arxiv DOIs excluded — not stable identifiers)
      2. Title similarity >= 0.9 with publication year within ±2

    Merge rules:
      - canonical = latest version (highest year, tiebreak: highest cited_by_count)
      - cited_by_count = sum across all versions
      - type = highest priority (author > mutual > citing > reference)
      - metadata (title, venue, doi, url, date) = from canonical
      - incoming edges = union (all papers that cited any version → canonical)
      - outgoing edges = only from canonical (latest version's references)
    """
    def normalize_doi(doi):
        if not doi:
            return None
        d = doi.lower().strip()
        d = re.sub(r'^https?://doi\.org/', '', d)
        if d.startswith('10.48550/'):
            return None  # arxiv preprint DOI, not a stable identifier
        return d or None

    node_list = list(nodes.values())

    # --- Union-Find ---
    parent = {n['id']: n['id'] for n in node_list}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(a, b):
        ra, rb = find(a), find(b)
        if ra != rb:
            parent[rb] = ra

    # Phase 1a: DOI-based merging
    print(f"  Version merging: checking DOIs for {len(node_list)} nodes...")
    doi_index = {}
    doi_matches = 0
    for n in node_list:
        doi = normalize_doi(n.get('doi'))
        if doi:
            if doi in doi_index:
                union(doi_index[doi], n['id'])
                doi_matches += 1
            else:
                doi_index[doi] = n['id']
    print(f"  DOI matches: {doi_matches}")

    # Phase 1b: fuzzy title merging within same first-author last name + year ±2
    def first_author_lastname(authors_str):
        if not authors_str:
            return None
        # "Last Name et al." or "Full Name" — take the last word before " et al." or end
        name = authors_str.split(' et al.')[0].strip()
        return name.split()[-1].lower() if name else None

    # Index by (lastname, year) bucket
    lastname_year_index: Dict[tuple, list] = {}
    for n in node_list:
        if not n.get('year') or not n.get('title'):
            continue
        ln = first_author_lastname(n.get('authors'))
        if ln:
            for dy in range(-2, 3):
                lastname_year_index.setdefault((ln, n['year'] + dy), []).append(n)

    checked_pairs: set = set()
    fuzzy_matches = 0
    candidates = [n for n in node_list if n.get('year') and n.get('title') and first_author_lastname(n.get('authors'))]
    print(f"  Fuzzy title matching for {len(candidates)} nodes (same first-author last name + year ±2)...")
    for n in candidates:
        ln = first_author_lastname(n['authors'])
        for other in lastname_year_index.get((ln, n['year']), []):
            if other['id'] == n['id']:
                continue
            pair = (min(n['id'], other['id']), max(n['id'], other['id']))
            if pair in checked_pairs:
                continue
            checked_pairs.add(pair)
            other_title = other.get('title') or ''
            if not other_title:
                continue
            sim = difflib.SequenceMatcher(None, n['title'].lower(), other_title.lower()).ratio()
            if sim >= 0.9:
                union(n['id'], other['id'])
                fuzzy_matches += 1
    print(f"  Fuzzy matches: {fuzzy_matches}")

    # Phase 2: collect groups
    groups: Dict[str, list] = {}
    for n in node_list:
        groups.setdefault(find(n['id']), []).append(n)

    # Phase 3: merge each group
    id_remap: Dict[str, str] = {}
    new_nodes: dict = {}
    n_merged = 0

    for group in groups.values():
        if len(group) == 1:
            new_nodes[group[0]['id']] = group[0]
            continue

        n_merged += len(group) - 1
        # Canonical = latest version
        group_sorted = sorted(
            group,
            key=lambda n: (n.get('year') or 0, n.get('cited_by_count') or 0),
            reverse=True
        )
        canonical = group_sorted[0]
        cid = canonical['id']

        for n in group_sorted[1:]:
            id_remap[n['id']] = cid

        total_cited = sum(n.get('cited_by_count') or 0 for n in group)
        best_type = max(
            (n.get('type', 'reference') for n in group),
            key=lambda t: TYPE_PRIORITY.get(t, 0)
        )
        new_nodes[cid] = {**canonical, 'cited_by_count': total_cited, 'type': best_type}

    # Phase 4: remap edges
    # - Outgoing edges from non-canonical (old) versions → DROP (use only latest refs)
    # - Incoming edges to non-canonical versions → remap target to canonical
    new_edges: set = set()
    for from_id, to_id in edges:
        if from_id in id_remap:
            continue  # drop old version's outgoing references
        new_to = id_remap.get(to_id, to_id)
        if from_id != new_to:
            new_edges.add((from_id, new_to))

    print(f"Version merging: collapsed {n_merged} duplicate nodes")
    return new_nodes, new_edges


def main():
    parser = argparse.ArgumentParser(description="Fetch citation network from OpenAlex")
    parser.add_argument("--id",   required=True, help="OpenAlex author ID (e.g. A5093400185)")
    parser.add_argument("--name", default="",    help="Author display name (for logging)")
    args = parser.parse_args()

    print("Starting citation network fetch...")
    start_time = time.time()

    # Configuration
    AUTHOR_ID = args.id
    DEPTH = 1
    MIN_CITATIONS_FOR_EXPANSION = 20

    if DEPTH != 1:
        print(f"Warning: DEPTH={DEPTH} is set but this script only implements depth 1. Level 2+ will be skipped.")
    EMAIL = "researcher@example.com"  # Being polite to OpenAlex

    # Storage
    nodes = {}  # work_id -> node_data
    edges = set()  # (from_id, to_id) tuples

    # Step 1: Fetch author profile
    print("Fetching author profile...")
    author_url = f"https://api.openalex.org/authors/{AUTHOR_ID}?mailto={EMAIL}"
    author_data = fetch_with_retry(author_url)

    if not author_data:
        print("Failed to fetch author data")
        return

    author_info = {
        'name': author_data.get('display_name', 'Unknown'),
        'openalex_id': AUTHOR_ID,
        'institution': (
            (author_data.get('last_known_institutions') or [{}])[0].get('display_name')
            or (author_data.get('last_known_institution') or {}).get('display_name')
            or 'Unknown'
        ),
        'total_citations': author_data.get('cited_by_count', 0),
        'h_index': author_data.get('h_index', 0),
        'works_count': author_data.get('works_count', 0)
    }

    print(f"Author: {author_info['name']}, {author_info['institution']}, {author_info['total_citations']} citations, h-index {author_info['h_index']}")

    # Step 2: Fetch all works by this author
    print(f"Fetching author's {author_info['works_count']} works...")
    author_works = []
    cursor = "*"

    while cursor:
        works_url = f"https://api.openalex.org/works?filter=author.id:{AUTHOR_ID}&sort=cited_by_count:desc&per_page=200&cursor={cursor}&mailto={EMAIL}"
        works_data = fetch_with_retry(works_url)

        if not works_data:
            print("Failed to fetch works data")
            break

        batch_works = works_data.get('results', [])
        author_works.extend(batch_works)

        cursor = works_data.get('meta', {}).get('next_cursor')
        print(f"  Fetched {len(batch_works)} works (total: {len(author_works)})")

        if not cursor:
            break

    print(f"Found {len(author_works)} author works")

    # Add author works to nodes
    for i, work in enumerate(author_works, 1):
        node = create_work_node(work, 'author')
        nodes[node['id']] = node
        title = node['title']
        title_display = title[:80] + ("..." if len(title) > 80 else "")
        print(f"  {i}. {title_display} ({node['cited_by_count']} citations)")

    # Step 3: Fetch citing papers for each author work — parallel
    cited_works = [w for w in author_works if w.get('cited_by_count', 0) > 0]
    skipped = len(author_works) - len(cited_works)
    print(
        f"\nFetching citing papers for {len(cited_works)} works "
        f"({skipped} skipped — 0 citations), {MAX_WORKERS} workers in parallel..."
    )

    total_citing_papers = 0

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        future_to_work = {
            executor.submit(_fetch_citing_for_work, (work, EMAIL)): work
            for work in cited_works
        }

        for i, future in enumerate(as_completed(future_to_work), 1):
            work = future_to_work[future]
            work_title = work.get('title', 'Unknown')[:50]
            try:
                work_id, citing_nodes, citing_edges = future.result()
                total_citing_papers += len(citing_nodes)
                print(f"  [{i}/{len(cited_works)}] {work_title}: {len(citing_nodes)} citers")

                for citing_node in citing_nodes:
                    citing_id = citing_node['id']
                    if citing_id not in nodes:
                        nodes[citing_id] = citing_node
                    elif nodes[citing_id]['type'] not in ['author']:
                        nodes[citing_id]['type'] = 'citing'

                edges.update(citing_edges)
            except Exception as e:
                print(f"  Error processing {work_title}: {e}")

    print(f"Completed citing papers fetch. Total citing papers: {total_citing_papers}")
    print(f"Current nodes: {len(nodes)}, edges: {len(edges)}")

    # Step 4: Fetch referenced papers for each author work
    print(f"\nFetching references for {len(author_works)} works...")

    all_reference_ids = set()
    work_to_refs = {}  # work_id -> list of referenced work ids

    for i, work in enumerate(author_works, 1):
        work_id = extract_work_id(work.get('id', ''))
        work_title = work.get('title', 'Unknown')[:50]

        referenced_works = work.get('referenced_works', [])
        ref_ids = [extract_work_id(ref_url) for ref_url in referenced_works if ref_url]

        work_to_refs[work_id] = ref_ids
        all_reference_ids.update(ref_ids)

        print(f"  [{i}/{len(author_works)}] {work_title}... → {len(ref_ids)} references")

    # Bulk fetch reference metadata — parallel
    ref_id_list = list(all_reference_ids)
    batch_size = 50  # OpenAlex limit for OR queries
    batches = [ref_id_list[i:i+batch_size] for i in range(0, len(ref_id_list), batch_size)]

    print(
        f"Bulk fetching metadata for {len(all_reference_ids)} unique references "
        f"in {len(batches)} batches, {MAX_WORKERS} workers in parallel..."
    )

    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        future_to_batch = {
            executor.submit(_fetch_reference_batch, (batch, EMAIL)): idx
            for idx, batch in enumerate(batches)
        }

        for future in as_completed(future_to_batch):
            idx = future_to_batch[future]
            try:
                ref_nodes = future.result()
                for ref_node in ref_nodes:
                    ref_id = ref_node['id']
                    if ref_id not in nodes:
                        nodes[ref_id] = ref_node
                    elif nodes[ref_id]['type'] not in ['author', 'citing']:
                        nodes[ref_id]['type'] = 'reference'
                print(f"    Processed batch {idx + 1}/{len(batches)}")
            except Exception as e:
                print(f"    Error in reference batch {idx + 1}: {e}")

    # Add reference edges
    for author_work_id, ref_ids in work_to_refs.items():
        for ref_id in ref_ids:
            if ref_id in nodes:  # Only add edge if we have the reference node
                edges.add((author_work_id, ref_id))

    print(f"Added {len(work_to_refs)} reference relationships")

    # Reclassify mutual nodes a posteriori: a non-author node is mutual if it
    # both cites an author work (edge: node → author) AND is cited by an author
    # work (edge: author → node). Derived from edges, not collection order.
    author_ids = {nid for nid, n in nodes.items() if n['type'] == 'author'}
    cites_author    = {f for f, t in edges if t in author_ids}
    cited_by_author = {t for f, t in edges if f in author_ids}
    mutual_ids = (cites_author & cited_by_author) - author_ids
    for nid in mutual_ids:
        nodes[nid]['type'] = 'mutual'
    print(f"Reclassified {len(mutual_ids)} mutual nodes")

    # Merge preprint/published version pairs
    nodes, edges = merge_versions(nodes, edges)

    # Remove orphaned nodes (no remaining edges) except author nodes.
    # These arise when a preprint's references were dropped in favour of the
    # published version's reference list, leaving some reference nodes stranded.
    connected = {nid for pair in edges for nid in pair}
    orphans = [nid for nid, n in nodes.items() if nid not in connected and n['type'] != 'author']
    for nid in orphans:
        del nodes[nid]
    if orphans:
        print(f"Removed {len(orphans)} orphaned nodes (no edges after version merging)")

    print(f"Final nodes: {len(nodes)}, edges: {len(edges)}")

    # Prepare output data
    nodes_list = list(nodes.values())
    edges_list = [{'from': from_id, 'to': to_id} for from_id, to_id in edges]

    citation_data = {
        'author': author_info,
        'nodes': nodes_list,
        'edges': edges_list,
        'metadata': {
            'depth': DEPTH,
            'fetched_at': datetime.now().isoformat(),
            'total_nodes': len(nodes_list),
            'total_edges': len(edges_list),
            'min_citations_for_expansion': MIN_CITATIONS_FOR_EXPANSION
        }
    }

    # Step 7: Save citation_data.json
    with open('citation_data.json', 'w', encoding='utf-8') as f:
        json.dump(citation_data, f, indent=2, ensure_ascii=False)

    print(f"\nSaved citation_data.json ({len(nodes_list)} nodes, {len(edges_list)} edges)")

    # Step 8: Save CSV file
    # Precompute cited_papers lookup in O(nodes + edges) instead of O(nodes * edges)
    author_titles = {n['id']: n['title'] for n in nodes_list if n['type'] == 'author'}
    cited_by_node: Dict[str, List[str]] = defaultdict(list)
    for edge in edges_list:
        if edge['to'] in author_titles:
            cited_by_node[edge['from']].append(author_titles[edge['to']])

    with open('citations.csv', 'w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f)
        writer.writerow(['title', 'authors', 'year', 'date', 'citation_count', 'venue', 'doi', 'url', 'type', 'cited_papers'])

        for node in nodes_list:
            writer.writerow([
                node['title'],
                node['authors'],
                node['year'],
                node['date'],
                node['cited_by_count'],
                node['venue'],
                node['doi'],
                node['url'],
                node['type'],
                '; '.join(cited_by_node.get(node['id'], []))
            ])

    print("Saved citations.csv")

    # Step 9: Print final summary
    end_time = time.time()
    duration = end_time - start_time

    print("\n" + "="*50)
    print("FINAL SUMMARY")
    print("="*50)
    print(f"Author: {author_info['name']}")
    print(f"Institution: {author_info['institution']}")
    print(f"Total citations: {author_info['total_citations']}")
    print(f"H-index: {author_info['h_index']}")
    print(f"Number of author works: {len([n for n in nodes_list if n['type'] == 'author'])}")
    print(f"Number of citing papers: {len([n for n in nodes_list if n['type'] == 'citing'])}")
    print(f"Number of referenced papers: {len([n for n in nodes_list if n['type'] == 'reference'])}")
    print(f"Total unique nodes: {len(nodes_list)}")
    print(f"Total edges: {len(edges_list)}")
    print(f"Total time: {duration/60:.1f} minutes")

if __name__ == "__main__":
    main()
